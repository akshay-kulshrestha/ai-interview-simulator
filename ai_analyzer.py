# Reverse index: question text -> (keywords, category). Built once at
# import time so generate_hints/analyze_answer can look up a question's
# expected concepts from just the text they're given (interview.py stores
# and passes back question_text, not a reference into the bank itself).
_QUESTION_INDEX = {}

for _role, _categories in QUESTION_BANK.items():
    for _category, _difficulties in _categories.items():
        for _difficulty, _questions in _difficulties.items():
            for _question_text, _keywords in _questions:
                _QUESTION_INDEX[_question_text] = (_keywords, _category)

for _difficulty, _questions in BEHAVIORAL_QUESTIONS.items():
    for _question_text, _keywords in _questions:
        _QUESTION_INDEX[_question_text] = (_keywords, "behavioral")


# ============================================================
# TF-IDF scoring model
# ============================================================
# Each question's expected keywords are turned into a short "reference
# concept document". A single TfidfVectorizer is fit across ALL of these
# reference documents at import time -- fitting on the whole bank rather
# than per-question is what makes the IDF half of TF-IDF meaningful: a
# term that shows up in most questions' references (e.g. common
# engineering words) gets down-weighted, while a term distinctive to one
# specific question's concepts gets weighted more heavily. bigrams are
# included so two-word technical terms ("time complexity", "race
# condition") are captured as a unit, not just their separate words.

_question_texts_ordered = list(_QUESTION_INDEX.keys())
_reference_docs = [
    " ".join(_QUESTION_INDEX[_q][0]) for _q in _question_texts_ordered
]

_VECTORIZER = TfidfVectorizer(
    tokenizer=_stemming_tokenizer,
    token_pattern=None,
    ngram_range=(1, 2),
    stop_words=_STEMMED_STOP_WORDS,
)
_REFERENCE_MATRIX = _VECTORIZER.fit_transform(_reference_docs)

# question text -> row index into _REFERENCE_MATRIX, so analyze_answer
# can grab the right reference vector for whichever question it's scoring.
_QUESTION_ROW = {
    _q: _i for _i, _q in enumerate(_question_texts_ordered)
}


