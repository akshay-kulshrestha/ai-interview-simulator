def _stem(word):
    """Minimal, dependency-free suffix stripping so that e.g. "decorators"
    and "decorator", or "closures" and "closure", are treated as the same
    term by the vectorizer below. Plain TfidfVectorizer does no stemming
    at all, so without this, a perfectly on-topic answer that happens to
    use the plural/verb form of a reference concept scores zero overlap
    on that term -- this isn't a full linguistic stemmer (that's what a
    library like nltk's PorterStemmer is for), just enough suffix
    handling to catch the common English cases that actually show up in
    short technical answers."""
    if len(word) > 4 and word.endswith("ies"):
        return word[:-3] + "y"
    if len(word) > 4 and word.endswith("es") and word[-3] in "sxz":
        return word[:-2]
    if len(word) > 3 and word.endswith("s") and not word.endswith("ss"):
        word = word[:-1]
    if len(word) > 5 and word.endswith("ing"):
        stem = word[:-3]
        if len(stem) > 2 and stem[-1] == stem[-2] and stem[-1] not in "aeiou":
            stem = stem[:-1]
        return stem
    if len(word) > 4 and word.endswith("ed"):
        stem = word[:-2]
        if len(stem) > 2 and stem[-1] == stem[-2] and stem[-1] not in "aeiou":
            stem = stem[:-1]
        return stem
    return word


_TOKEN_PATTERN = re.compile(r"[a-zA-Z]+(?:-[a-zA-Z]+)?")


def _stemming_tokenizer(text):
    return [_stem(tok.lower()) for tok in _TOKEN_PATTERN.findall(text)]


# sklearn's built-in "english" stop word list is plain, unstemmed text --
# since every vocabulary token here goes through _stem() first, the stop
# words need the same treatment, or common words survive filtering under
# their stemmed form (and sklearn warns about exactly this mismatch).
from sklearn.feature_extraction.text import ENGLISH_STOP_WORDS as _RAW_STOP_WORDS  # noqa: E402

_STEMMED_STOP_WORDS = list({_stem(w) for w in _RAW_STOP_WORDS})

