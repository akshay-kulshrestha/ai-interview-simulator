"""Local question generation and TF-IDF/ML-based answer analysis.

No external service of any kind -- no Ollama server, no cloud AI API, no
network calls, no API keys. Questions come from a curated local question
bank. Answers are scored with a real, if lightweight, NLP/ML technique:
each question has a reference "concept document" built from its expected
keywords, a TF-IDF vectorizer is fit across all of them at import time so
term weighting reflects which concepts are actually distinctive across
the whole question bank (not just this one question), and each answer is
scored by its cosine similarity to its question's reference vector. This
is a genuine vector-space model, not string matching -- it naturally
rewards partial/paraphrased overlap and down-weights generic words that
appear in every reference document, unlike a hardcoded "must contain
this literal keyword" check.

This module has gone through Ollama (local-only), Anthropic (requires
paid credits), and Gemini (free tier, but unstable model availability/
quotas) before landing here: fully local, zero cost, zero external
dependency at runtime, deployable anywhere -- while still doing real
machine learning rather than just keyword substring matching.

Because there's no remote model to call, num_predict/max_tokens-style
knobs, retries, and JSON-repair helpers from the earlier versions are
gone -- there's no malformed or truncated output to repair, since nothing
is being generated by anything other than this file's own code.
"""

import logging
