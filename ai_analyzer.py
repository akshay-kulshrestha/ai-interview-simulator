def warm_up():
    """The TF-IDF vectorizer is already fit at import time (see the
    module-level _VECTORIZER/_REFERENCE_MATRIX setup above) -- there's no
    lazy loading or external service to warm up here. This just confirms
    it's ready and logs the vocabulary size, so app.py's startup call
    (and the /api/warmup endpoint) still do something meaningful to check."""
    log.info(
        "Local TF-IDF scoring model ready -- %d questions, %d-term "
        "vocabulary.", len(_QUESTION_INDEX), len(_VECTORIZER.vocabulary_),
    )


def generate_question(role, difficulty, category, personality, previous_questions, topics=None):
    """Pick a question from the local bank for this role/category/
    difficulty that hasn't already been asked this session, if possible."""

    if category == "behavioral":
        pool = BEHAVIORAL_QUESTIONS.get(difficulty, [])
    else:
        role_bank = QUESTION_BANK.get(role)
        if role_bank is None:
            log.warning("Unknown role %r, falling back to behavioral pool", role)
            pool = BEHAVIORAL_QUESTIONS.get(difficulty, [])
        else:
            pool = role_bank.get(category, {}).get(difficulty, [])

    if not pool:
        # Shouldn't happen with the roles/categories/difficulties this
        # app actually offers, but degrade gracefully rather than crash
        # a live session if it ever does.
        log.error(
            "No questions available for role=%s category=%s difficulty=%s",
            role, category, difficulty,
        )
        return "Tell me about a project you've worked on recently."

    asked = set(previous_questions or [])
    unused = [(q, kw) for q, kw in pool if q not in asked]

    question_text, _keywords = random.choice(unused) if unused else random.choice(pool)

    log.info(
        "Selected %s question: role=%s difficulty=%s category=%s",
        "unused" if unused else "repeat (pool exhausted)",
        role, difficulty, category,
    )
    return question_text


def generate_hints(role, question_text, difficulty):
    """Structural hints (always shown) plus one topic nudge pulled from
    the question's expected concepts, if the question is recognized."""

    hints = list(GENERIC_FALLBACK_HINTS)

    entry = _QUESTION_INDEX.get(question_text)
    if entry:
        keywords, _category = entry
        if keywords:
            topic = random.choice(keywords)
            hints.append(f"Consider how \"{topic}\" relates to your answer.")

    return hints[:MAX_HINTS]


def _score_answer(question_text, answer, keywords):
    """Score 0-10 from two signals: TF-IDF cosine similarity between the
    answer and the question's reference concept vector (the real ML
    component -- a continuous, term-weighted similarity, not a binary
    keyword check), and how developed (not just long) the answer is.

    Also returns matched/missing keyword lists -- these are a separate,
    literal substring check used only to generate readable strengths/
    suggestions text ("you mentioned X", "you didn't mention Y"), since
    a cosine similarity score alone can't be turned into that kind of
    concrete, human-readable feedback. The score itself comes from the
    similarity, not from this list."""

    row = _QUESTION_ROW.get(question_text)
    if row is not None:
        answer_vector = _VECTORIZER.transform([answer])
        similarity = float(cosine_similarity(answer_vector, _REFERENCE_MATRIX[row])[0, 0])
    else:
        # Question not in the bank (see analyze_answer's fallback path) --
        # shouldn't reach here in practice since that path returns early,
        # but fall back to a neutral similarity rather than crash.
        similarity = 0.5

    lowered = answer.lower()
    matched = [kw for kw in keywords if kw.lower() in lowered]
    missing = [kw for kw in keywords if kw not in matched]

    word_count = len(re.findall(r"[A-Za-z0-9']+", answer))
    length_component = min(1.0, word_count / DEVELOPED_ANSWER_WORDS)

    # The length bonus is GATED by similarity (multiplicative, not
    # additive) rather than length being an independent point source --
    # a purely additive formula lets any sufficiently long answer earn
    # up to 3 points regardless of topic, which let a long, completely
    # off-topic answer outscore a short but genuinely on-topic one in
    # testing. Scaling the length bonus by similarity means development
    # only pays off once the answer is actually about the right thing.
    raw = similarity * (7 + length_component * 3)
    score = max(MIN_SCORE, min(MAX_SCORE, round(raw)))

    return score, matched, missing


_STRENGTH_TEMPLATES = {
    "friendly": "Nice, you touched on {kw} — that's an important part of this.",
    "professional": "The answer appropriately addressed {kw}.",
    "strict": "The mention of {kw} was correctly identified as relevant.",
}
_SUGGESTION_TEMPLATES = {
    "friendly": "It'd be even stronger if you also mentioned {kw}.",
    "professional": "Consider addressing {kw} for a more complete answer.",
    "strict": "Discussion of {kw} was expected and should have been addressed.",
}
_GENERIC_STRENGTHS = {
    "friendly": "You engaged directly with the question, which is a great start.",
    "professional": "The answer addressed the core of what the question asked.",
    "strict": "The answer attempted to engage with the question directly.",
}
_GENERIC_SUGGESTIONS = {
    "friendly": "Try adding a bit more detail or a concrete example next time.",
    "professional": "Add more detail and structure to fully answer the question.",
    "strict": "The answer lacked sufficient depth and concrete detail.",
}


def analyze_answer(role, question, answer, personality):
    word_count = len(re.findall(r"[A-Za-z0-9']+", answer))

    if word_count < MIN_ANSWER_WORDS:
        log.info(
            "Answer too short (%d words, need %d) for: %s",
            word_count, MIN_ANSWER_WORDS, question[:80],
        )
        return {
            "score": MIN_SCORE,
            "strengths": [],
            "suggestions": [
                "This answer is too short to evaluate -- please write a "
                "complete response that directly addresses the question."
            ],
            "improved_answer": "",
        }

    entry = _QUESTION_INDEX.get(question)
    if entry is None:
        # Question text wasn't recognized (e.g. saved from a previous
        # LLM-generated session, before this local version existed) --
        # fall back to a length-only assessment rather than failing.
        log.warning(
            "Question not found in local bank, scoring on length only: %s",
            question[:80],
        )
        length_component = min(1.0, word_count / DEVELOPED_ANSWER_WORDS)
        score = max(MIN_SCORE, min(MAX_SCORE, round(length_component * 10)))
        matched, missing = [], []
    else:
        keywords, _category = entry
        score, matched, missing = _score_answer(question, answer, keywords)

    strength_template = _STRENGTH_TEMPLATES.get(personality, _STRENGTH_TEMPLATES["professional"])
    suggestion_template = _SUGGESTION_TEMPLATES.get(personality, _SUGGESTION_TEMPLATES["professional"])

    strengths = [strength_template.format(kw=kw) for kw in matched[:MAX_STRENGTHS]]
    suggestions = [suggestion_template.format(kw=kw) for kw in missing[:MAX_SUGGESTIONS]]

    if not strengths:
        strengths = [_GENERIC_STRENGTHS.get(personality, _GENERIC_STRENGTHS["professional"])]
    if not suggestions:
        suggestions = [_GENERIC_SUGGESTIONS.get(personality, _GENERIC_SUGGESTIONS["professional"])]

    if missing:
        improved_answer = (
            "A stronger answer would also cover: " + ", ".join(missing[:MAX_SUGGESTIONS])
            + ". Try naming these explicitly and explaining how each one applies here."
        )
    elif word_count < THIN_ANSWER_WORDS:
        improved_answer = (
            "The right ideas are here -- develop them further with a concrete "
            "example or a brief explanation of trade-offs to make the answer "
            "more complete."
        )
    else:
        improved_answer = ""

    log.info("Answer scored %d/10 (%d/%d concepts matched)",
             score, len(matched), len(matched) + len(missing))

    return {
        "score": score,
        "strengths": strengths,
        "suggestions": suggestions,
        "improved_answer": improved_answer,
    }


_SUMMARY_TIERS = [
    (8, "an excellent overall performance"),
    (6, "a solid performance with room to grow"),
    (4, "a mixed performance"),
    (0, "an early-stage performance that would benefit from more practice"),
]


def generate_final_summary(role, personality, difficulty, average_score, answers):
    tier = next(label for threshold, label in _SUMMARY_TIERS if average_score >= threshold)

    scored = [a for a in (answers or []) if isinstance(a.get("score"), (int, float))]
    best = max(scored, key=lambda a: a["score"], default=None)
    worst = min(scored, key=lambda a: a["score"], default=None)

    sentences = [
        f"This {difficulty}-difficulty {role} interview showed {tier}, "
        f"averaging {average_score:.1f}/10 across {len(answers or [])} question(s)."
    ]

    if best is not None and best is not worst:
        sentences.append(
            f"The strongest response was to \"{best['question_text']}\", "
            f"scoring {best['score']}/10."
        )

    if worst is not None and worst is not best:
        sentences.append(
            f"The area with the most room to improve was the response to "
            f"\"{worst['question_text']}\" ({worst['score']}/10) -- "
            "revisiting that topic would be a good next step."
        )

    if average_score >= 7:
        sentences.append(
            "Overall, keep practicing to maintain this level under "
            "different question styles and difficulty tiers."
        )
    else:
        sentences.append(
            "Focus on naming specific concepts and trade-offs directly in "
            "your answers, rather than describing them only in general terms."
        )

    summary = " ".join(sentences)
    log.info("Generated final summary: role=%s avg_score=%.1f", role, average_score)
    return summary


def count_filler_words(text):
    """Return the total filler-word count and which ones occurred, used as a
    communication-quality signal alongside the content-coverage score."""
    lowered = text.lower()
    matched = []
    total = 0
    for phrase in FILLER_WORDS:
        count = len(re.findall(r"\b" + re.escape(phrase) + r"\b", lowered))
        if count:
            matched.append({"phrase": phrase, "count": count})
            total += count
    return total, matched
